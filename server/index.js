import 'dotenv/config';
import path from 'node:path';
import express from 'express';
import session from 'express-session';
import helmet from 'helmet';
import { db } from './db.js';
import { PrismaSessionStore } from './session-store.js';
import { auth,verifyCsrf } from './auth.js';
import { records } from './records.js';
import { media } from './media.js';
import { settings } from './settings.js';
import { backup } from './backup.js';
import { drafts } from './drafts.js';
import { tags } from './tags.js';

if(!process.env.DATABASE_URL||!process.env.SESSION_SECRET||process.env.SESSION_SECRET.length<32||!process.env.PUBLIC_BASE_URL)throw new Error('请配置 DATABASE_URL、SESSION_SECRET 和 PUBLIC_BASE_URL');
const app=express();
const basePath=(process.env.BASE_PATH||'').replace(/^\/+|\/+$/g,'');
if(basePath&&!/^[a-zA-Z0-9_-]+(?:\/[a-zA-Z0-9_-]+)*$/.test(basePath))throw new Error('BASE_PATH 无效');
const router=express.Router();
if(process.env.TRUST_PROXY==='1')app.set('trust proxy','loopback');
app.disable('x-powered-by');
app.use(helmet({contentSecurityPolicy:{directives:{defaultSrc:["'self'"],scriptSrc:["'self'"],styleSrc:["'self'","'unsafe-inline'"],imgSrc:["'self'",'data:','blob:','https://*.tile.openstreetmap.org'],connectSrc:["'self'"],fontSrc:["'self'",'data:'],frameSrc:["'self'"],objectSrc:["'none'"],upgradeInsecureRequests:process.env.NODE_ENV==='production'?[]:null}}}));
await db.$queryRawUnsafe('PRAGMA journal_mode = WAL');
const secureCookie=process.env.COOKIE_SECURE==='true'||(process.env.NODE_ENV==='production'&&process.env.COOKIE_SECURE!=='false');
app.use(session({store:new PrismaSessionStore(),name:'space.sid',secret:process.env.SESSION_SECRET,resave:false,saveUninitialized:false,cookie:{httpOnly:true,sameSite:'strict',secure:secureCookie,path:basePath?'/'+basePath:'/',maxAge:12*60*60*1000}}));
router.use(verifyCsrf);
router.use((req,res,next)=>express.json({limit:req.path==='/api/backup/restore'?'120mb':'2mb'})(req,res,next));
router.get('/api/health',async(req,res)=>{try{await db.$queryRaw`SELECT 1`;res.json({ok:true});}catch{res.status(503).json({ok:false});}});
router.get('/api/links',(req,res)=>{let base='';try{const url=new URL(process.env.LEGACY_BASE_URL);if(['http:','https:'].includes(url.protocol)&&!url.username&&!url.password)base=url.origin+url.pathname.replace(/\/$/,'');}catch{}res.json({douyin:base+'/douyin/',files:base+'/files/'});});
router.use('/api/auth',auth);
router.use('/api/records',records);
router.use('/api/media',media);
router.use('/api/settings',settings);
router.use('/api/backup',backup);
router.use('/api/drafts',drafts);
router.use('/api/tags',tags);
router.use('/api',(req,res)=>res.status(404).json({error:'接口不存在'}));
const dist=path.resolve(process.env.DIST_DIR||'dist');
router.use(express.static(dist,{index:false,maxAge:process.env.NODE_ENV==='production'?'1h':0}));
router.get('/{*path}',(req,res)=>res.sendFile(path.join(dist,'index.html'),err=>{if(err&&!res.headersSent)res.status(503).send('前端尚未构建，请运行 npm run build');}));
app.use(basePath?'/'+basePath:'/',router);
app.use((err,req,res,next)=>{console.error('Request failed:',err.code||err.name);if(res.headersSent)return next(err);if(err.code==='LIMIT_FILE_SIZE')return res.status(413).json({error:'图片不能超过 10 MB'});if(err.type==='entity.too.large')return res.status(413).json({error:'文件超过大小限制'});res.status(500).json({error:'服务暂时不可用，请查看服务日志'});});
const port=Number(process.env.PORT||3070),host=process.env.HOST||'127.0.0.1';
app.listen(port,host,()=>console.log(`Digital space: http://${host}:${port}`));
for(const sig of ['SIGINT','SIGTERM'])process.on(sig,async()=>{await db.$disconnect();process.exit(0);});
